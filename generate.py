"""Generate a GitHub profile with Python 3.11+ and no third-party dependencies."""
import argparse
import html
import json
import os
from pathlib import Path
import re
import subprocess
import sys
import urllib.request

ROOT = Path(__file__).resolve().parent

def api(path):
    token = os.getenv("GH_TOKEN") or os.getenv("GITHUB_TOKEN")
    if token:
        request = urllib.request.Request("https://api.github.com/" + path, headers={
            "Authorization": "Bearer " + token, "Accept": "application/vnd.github+json",
            "User-Agent": "systems-lab-profile", "X-GitHub-Api-Version": "2022-11-28"})
        with urllib.request.urlopen(request, timeout=30) as response:
            return json.load(response)
    try:
        result = subprocess.run(["gh", "api", path], capture_output=True, text=True, check=True)
        return json.loads(result.stdout)
    except FileNotFoundError:
        request = urllib.request.Request("https://api.github.com/" + path,
                                         headers={"User-Agent": "systems-lab-profile"})
        with urllib.request.urlopen(request, timeout=30) as response:
            return json.load(response)

def fetch_repos(username):
    repos = []
    page = 1
    while True:
        batch = api(f"users/{username}/repos?type=owner&per_page=100&page={page}")
        if not isinstance(batch, list):
            raise ValueError("GitHub did not return a repository list")
        repos.extend(batch)
        if len(batch) < 100:
            return repos
        page += 1

def public_repos(repos, username):
    # Explicit False makes incomplete fixture/API records fail closed.
    return sorted((r for r in repos if r.get("private") is False
                   and r.get("owner", {}).get("login", "").lower() == username.lower()),
                  key=lambda r: r["name"].lower())

def esc(value):
    return html.escape(str(value)).replace("|", "&#124;").replace("\n", " ")

def render(config, repos):
    username = config["username"]
    visible = public_repos(repos, username)
    by_name = {r["name"]: r for r in visible}
    lines = ["<!-- Generated by generate.py. Edit profile.json, then regenerate. -->",
             '![Faris / Systems Lab — Backend, applied AI, useful software](assets/header.svg)',
             f'# {esc(config["tagline"])}',
             f'**{esc(config["name"])}** · Bhatkal, India · Building at **Omnimate**',
             esc(config["intro"]),
             f'[Explore the code](https://github.com/{username}?tab=repositories) · '
             f'[LinkedIn]({config["linkedin"]}) · [Start a conversation](mailto:{config["email"]})',
             '---', '## The lab, in four experiments',
             'Each project starts with an input. The interesting part is what happens next.']
    for project in config["featured"]:
        if project["repo"] not in by_name:
            continue
        url = by_name[project["repo"]]["html_url"]
        lines += [f'### {esc(project["label"])} · [{esc(project["title"])}]({url})',
                  esc(project["description"]), f'`{project["pipeline"]}`',
                  f'<sub>{esc(project["stack"])}</sub>']
    lines += ['---', '## Beyond the public repositories',
              'A wider collection of projects from my portfolio, spanning voice, security, and everyday workflows.']
    for category in dict.fromkeys(p["category"] for p in config["external_projects"]):
        lines += [f'### {esc(category)}']
        for project in config["external_projects"]:
            if project["category"] == category:
                lines += [f'**{esc(project["name"])}** — {esc(project["description"])}']
    lines += ['---', '## How I think about building',
              '> Start with the workflow. Give the data a shape. Make the result useful.',
              '- **Backend:** APIs, data models, access boundaries, and traceable state changes.\n'
              '- **Applied AI:** computer vision and automation connected to usable interfaces.\n'
              '- **Product:** clear paths from a messy input to a meaningful next action.',
              '<details>\n<summary><b>Open the repository index</b></summary>',
              f'{len(visible)} public owned repositories. Refreshed by the generator; private repositories are excluded.',
              '| Repository | Field note | Main language |\n| :--- | :--- | :--- |']
    for repo in visible:
        note = config["repository_notes"].get(repo["name"], repo.get("description") or "New entry in the lab.")
        if repo.get("fork"):
            note = "Fork · " + note
        if repo.get("archived"):
            note = "Archived · " + note
        lines.append(f'| [{esc(repo["name"])}]({repo["html_url"]}) | {esc(note)} | {esc(repo.get("language") or "—")} |')
    lines += ['</details>', '---', '**Have a workflow that deserves better software?**',
              f'[Let’s build it.](mailto:{config["email"]})',
              '<sub>Built with intent. Updated from source. Always another experiment.</sub>']
    return "\n\n".join(lines).replace(" |\n\n|", " |\n|") + "\n"

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repos", type=Path, help="Offline GitHub API JSON fixture")
    parser.add_argument("--output", type=Path, default=ROOT / "README.md")
    args = parser.parse_args()
    config = json.loads((ROOT / "profile.json").read_text(encoding="utf-8-sig"))
    if not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9-]{0,38}", config["username"]):
        raise ValueError("Invalid GitHub username")
    repos = json.loads(args.repos.read_text(encoding="utf-8-sig")) if args.repos else fetch_repos(config["username"])
    content = render(config, repos)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    temp = args.output.with_suffix(".tmp")
    temp.write_text(content, encoding="utf-8", newline="\n")
    temp.replace(args.output)
    print(f"Generated {args.output.name}: {len(public_repos(repos, config['username']))} public repos, "
          f"{len(config['external_projects'])} additional projects")

if __name__ == "__main__":
    try:
        main()
    except Exception as error:
        print(f"Generation failed; existing README preserved: {error}", file=sys.stderr)
        sys.exit(1)
