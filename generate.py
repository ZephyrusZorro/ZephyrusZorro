"""Generate a GitHub profile with Python 3.11+ and no third-party dependencies."""
import argparse
import html
import json
import os
from pathlib import Path
import re
import subprocess
import sys
import urllib.request

ROOT = Path(__file__).resolve().parent

def api(path):
    token = os.getenv("GH_TOKEN") or os.getenv("GITHUB_TOKEN")
    if token:
        request = urllib.request.Request("https://api.github.com/" + path, headers={
            "Authorization": "Bearer " + token, "Accept": "application/vnd.github+json",
            "User-Agent": "systems-lab-profile", "X-GitHub-Api-Version": "2022-11-28"})
        with urllib.request.urlopen(request, timeout=30) as response:
            return json.load(response)
    try:
        result = subprocess.run(["gh", "api", path], capture_output=True, text=True, check=True)
        return json.loads(result.stdout)
    except FileNotFoundError:
        request = urllib.request.Request("https://api.github.com/" + path,
                                         headers={"User-Agent": "systems-lab-profile"})
        with urllib.request.urlopen(request, timeout=30) as response:
            return json.load(response)

def fetch_repos(username):
    repos = []
    page = 1
    while True:
        batch = api(f"users/{username}/repos?type=owner&per_page=100&page={page}")
        if not isinstance(batch, list):
            raise ValueError("GitHub did not return a repository list")
        repos.extend(batch)
        if len(batch) < 100:
            return repos
        page += 1

def public_repos(repos, username):
    # Explicit False makes incomplete fixture/API records fail closed.
    return sorted((r for r in repos if r.get("private") is False
                   and r.get("owner", {}).get("login", "").lower() == username.lower()),
                  key=lambda r: r["name"].lower())

def esc(value):
    return html.escape(str(value)).replace("|", "&#124;").replace("\n", " ")

def render(config, repos):
    username = config["username"]
    visible = public_repos(repos, username)
    by_name = {r["name"]: r for r in visible}
    projects = [r for r in visible if r["name"].lower() != username.lower()]
    languages = sorted({r["language"] for r in projects if r.get("language")})
    lines = ["<!-- Generated by generate.py. Edit profile.json, then regenerate. -->",
             '<h1 align="center">Hi, I’m Faris 👋</h1>',
             '<p align="center"><b>Backend Developer · Applied AI · SaaS Builder</b></p>',
             '<p align="center">Building useful software from real-world problems.</p>',
             f'<p align="center"><a href="{config["linkedin"]}">LinkedIn</a> &nbsp;·&nbsp; '
             f'<a href="mailto:{config["email"]}">Email</a> &nbsp;·&nbsp; '
             f'<a href="https://github.com/{username}/portfolio">Portfolio</a></p>',
             '---', '### A little about me',
             '- 🎓 Studying **Artificial Intelligence & Machine Learning** at AITM.\n'
             '- 🛠 Building at **Omnimate**, with a focus on backend systems and automation.\n'
             '- 🧠 Interested in applied AI, computer vision, and practical software workflows.\n'
             '- 📍 Based in **Bhatkal, India**.',
             '### Tech stack',
             '**Languages**\n\n![Python · TypeScript · JavaScript · SQL](assets/languages.svg)',
             '**Backend & interfaces**\n\n![FastAPI · Node.js · React · Next.js](assets/development.svg)',
             '**Applied AI & tooling**\n\n![OpenCV · MediaPipe · scikit-learn · Docker · Git](assets/tooling.svg)',
             '### Selected work',
             '| Project | What I’m building | Stack |\n| :--- | :--- | :--- |']
    for project in config["featured"]:
        if project["repo"] in by_name:
            lines.append(f'| **[{esc(project["title"])}]({by_name[project["repo"]]["html_url"]})** | '
                         f'{esc(project["description"])} | {esc(project["stack"])} |')
    lines += ['### Beyond GitHub',
              'More projects from my portfolio — voice, automation, security, and everyday tools.',
              '| Project | In a sentence |\n| :--- | :--- |']
    for project in config["external_projects"]:
        lines.append(f'| **{esc(project["name"])}** | {esc(project["description"])} |')
    lines += ['### The way I build',
              '```text\nUnderstand the problem → Design the workflow → Build → Test → Refine\n```',
              'Clear APIs. Thoughtful interfaces. AI with a practical purpose.',
              '### GitHub at a glance',
              f'**{len(projects)} public project repositories** · **{len(config["external_projects"])} additional portfolio projects**',
              'Main repository languages: ' + ' · '.join(f'**{esc(x)}**' for x in languages) + '.',
              '<details>\n<summary>Browse all public repositories</summary>',
              '| Repository | Description |\n| :--- | :--- |']
    for repo in visible:
        note = config["repository_notes"].get(repo["name"], repo.get("description") or "New project.")
        if repo["name"].lower() == username.lower():
            note = "This profile and its automatic README generator."
        if repo.get("fork"):
            note = "Fork · " + note
        if repo.get("archived"):
            note = "Archived · " + note
        lines.append(f'| [{esc(repo["name"])}]({repo["html_url"]}) | {esc(note)} |')
    lines += ['</details>', '---',
              '<p align="center"><b>Have something interesting to build?</b><br>'
              f'<a href="mailto:{config["email"]}">Let’s talk.</a></p>']
    return "\n\n".join(lines).replace(" |\n\n|", " |\n|") + "\n"

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repos", type=Path, help="Offline GitHub API JSON fixture")
    parser.add_argument("--output", type=Path, default=ROOT / "README.md")
    args = parser.parse_args()
    config = json.loads((ROOT / "profile.json").read_text(encoding="utf-8-sig"))
    if not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9-]{0,38}", config["username"]):
        raise ValueError("Invalid GitHub username")
    repos = json.loads(args.repos.read_text(encoding="utf-8-sig")) if args.repos else fetch_repos(config["username"])
    content = render(config, repos)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    temp = args.output.with_suffix(".tmp")
    temp.write_text(content, encoding="utf-8", newline="\n")
    temp.replace(args.output)
    print(f"Generated {args.output.name}: {len(public_repos(repos, config['username']))} public repos, "
          f"{len(config['external_projects'])} additional projects")

if __name__ == "__main__":
    try:
        main()
    except Exception as error:
        print(f"Generation failed; existing README preserved: {error}", file=sys.stderr)
        sys.exit(1)
